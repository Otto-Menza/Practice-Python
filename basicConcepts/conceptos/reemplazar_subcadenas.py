#Reemplazar subcadenas
#metodo replace
cadena = 'Hola Mundo!'
nueca_subcadena = cadena.replace('Mundo', 'a todos')
print(f'Cadena origina: {cadena}')
print(f'Nueva cadena reemplazada: {nueca_subcadena}')

# sustituir "hola" por adios:
adios_cadena = nueca_subcadena.replace('Hola', 'Adios')
print(f'Nueva cadena con adios: {adios_cadena}')