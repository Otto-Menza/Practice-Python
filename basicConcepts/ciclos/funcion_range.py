#funcion range en python
print('Secuencia de 0 a 4:')
# inicio = 0 (opcional)
# fin = 5 (5-1=4)
# incremento/salto = 1 (opcional)
for i in range(5):
    print(i, end=' ')

print('\n\nSecuencia del 10 al 20:')
for i in range(10,21):
    print(i, end=' ')
print('\n\nSecuencia del 20 al 30 de 2 en 2:')
for i in range(30,41,2):
    print(i, end=' ')