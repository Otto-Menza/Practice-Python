#Metodo de upper para mayusculas
cadena1 = 'Hola Mundo'
print(f'cadena original: {cadena1}')
mayusculas = cadena1.upper()
print(f'cadena en mayusculas: {mayusculas}')
#Metodo para minusculas
print(f'Cadena en minusculas: {mayusculas.lower()}')

# Quita espacios
cadena2 = ' juan Perez '
print('Cadena con espacios:',cadena2)
print(f'Cadena sin espacios: {cadena2.strip()}')